const https=require("https");

function parseRepo(value){
  const m=String(value||"").trim().match(/^([A-Za-z0-9_.-]+)\/([A-Za-z0-9_.-]+)$/);
  if(!m)throw Error("PUBLISH_REPO must be owner/repo");
  return {owner:m[1],repo:m[2]};
}
function safeBranch(slug){
  const s=String(slug||"").toLowerCase().replace(/[^a-z0-9-]/g,"-").replace(/-+/g,"-").replace(/^-|-$/g,"").slice(0,70);
  if(!s)throw Error("Valid article slug required");
  return "area-seo/article-"+s;
}
function createClient(opts={}){
  const token=String(opts.token||process.env.GITHUB_PUBLISH_TOKEN||"").trim();
  const repoFull=opts.repo||process.env.PUBLISH_REPO||"jmmeta6767/area-maibab-public-site";
  const baseBranch=opts.baseBranch||process.env.PUBLISH_BRANCH||"main";
  const {owner,repo}=parseRepo(repoFull);
  if(baseBranch!=="main")throw Error("Publisher base branch must be main");
  const request=opts.request||((method,path,body)=>new Promise((resolve,reject)=>{
    if(!token)return reject(Object.assign(Error("GITHUB_PUBLISH_TOKEN is not configured"),{status:503}));
    const payload=body===undefined?null:JSON.stringify(body);
    const req=https.request({hostname:"api.github.com",path,method,headers:{
      "Accept":"application/vnd.github+json","Authorization":"Bearer "+token,
      "X-GitHub-Api-Version":"2022-11-28","User-Agent":"AREA-SEO-AI/1.9",
      ...(payload?{"Content-Type":"application/json","Content-Length":Buffer.byteLength(payload)}:{})
    }},res=>{let data="";res.on("data",c=>data+=c);res.on("end",()=>{
      let parsed={};try{parsed=data?JSON.parse(data):{}}catch{parsed={message:data}}
      if(res.statusCode>=200&&res.statusCode<300)return resolve({status:res.statusCode,data:parsed});
      const e=Error(parsed.message||("GitHub HTTP "+res.statusCode));e.statusCode=res.statusCode;e.response=parsed;reject(e);
    })});
    req.setTimeout(20000,()=>req.destroy(Error("GitHub publisher timeout")));req.on("error",reject);if(payload)req.write(payload);req.end();
  }));
  const api=p=>"/repos/"+encodeURIComponent(owner)+"/"+encodeURIComponent(repo)+p;
  async function getJson(path){return (await request("GET",api(path))).data}
  const contentPath=p=>"/contents/"+String(p).split("/").map(encodeURIComponent).join("/");
  async function getPublishBase(slug){
    const base=await getJson("/git/ref/heads/"+encodeURIComponent(baseBranch)),baseSha=base.object?.sha;if(!baseSha)throw Error("Unable to resolve public-site main branch");
    const read=async p=>{const x=await getJson(contentPath(p)+"?ref="+encodeURIComponent(baseBranch));return{path:p,sha:x.sha,content:Buffer.from(x.content||"","base64").toString("utf8")}};
    const article="article-"+String(slug||"")+".html";let articleExists=false;try{await getJson(contentPath(article)+"?ref="+encodeURIComponent(baseBranch));articleExists=true}catch(e){if(e.statusCode!==404)throw e}
    const [articlesHtml,sitemapXml]=await Promise.all([read("articles.html"),read("sitemap.xml")]);return{baseSha,articleExists,articlesHtml,sitemapXml};
  }
  async function createPublishPR(item,pkg,options={}){
    if(!item||item.status!=="approved")throw Object.assign(Error("Draft must be approved before publishing"),{status:422});
    if(!pkg?.files?.length)throw Object.assign(Error("Publisher package is empty"),{status:422});
    const allowed=new Set([pkg.article?.filename,"articles.html","sitemap.xml"]);
    if(pkg.files.some(f=>!allowed.has(f.path)))throw Object.assign(Error("Publisher package contains an unexpected path"),{status:422});
    const branch=safeBranch(item.slug),base=await getJson("/git/ref/heads/"+encodeURIComponent(baseBranch));
    const baseSha=base.object?.sha;if(!baseSha)throw Error("Unable to resolve public-site main branch");
    if(options.expectedBaseSha&&options.expectedBaseSha!==baseSha)throw Object.assign(Error("Public site main changed; rebuild package and retry"),{status:409});
    let branchExists=false;
    try{await getJson("/git/ref/heads/"+encodeURIComponent(branch));branchExists=true}catch(e){if(e.statusCode!==404)throw e}
    if(!branchExists)await request("POST",api("/git/refs"),{ref:"refs/heads/"+branch,sha:baseSha});
    const written=[];
    for(const file of pkg.files){
      let sha;try{const cur=await getJson(contentPath(file.path)+"?ref="+encodeURIComponent(branch));sha=cur.sha}catch(e){if(e.statusCode!==404)throw e}
      const payload={message:"seo: publish "+item.slug+" ("+file.path+")",content:Buffer.from(file.content,"utf8").toString("base64"),branch};
      if(sha)payload.sha=sha;
      const out=await request("PUT",api(contentPath(file.path)),payload);written.push({path:file.path,commit:out.data.commit?.sha||null});
    }
    const pulls=await getJson("/pulls?state=open&head="+encodeURIComponent(owner+":"+branch)+"&base="+encodeURIComponent(baseBranch));
    let pr=Array.isArray(pulls)&&pulls[0];
    if(!pr){
      const out=await request("POST",api("/pulls"),{title:"SEO: "+item.title,head:branch,base:baseBranch,body:"Generated by AREA SEO AI after SEO audit and human approval.\
\
Article: "+pkg.article.filename+"\
\
Review the diff and CI before merging. Do not merge automatically."});
      pr=out.data;
    }
    return {mode:"pull-request",repository:repoFull,base:baseBranch,branch,baseSha,files:written,pr:{number:pr.number,url:pr.html_url,title:pr.title},merged:false};
  }
  async function closePublishPR(number){const n=Number(number);if(!Number.isInteger(n)||n<1)throw Object.assign(Error("Valid pull request number required"),{status:400});const pr=await getJson("/pulls/"+n);if(pr.merged)throw Object.assign(Error("Merged pull requests cannot be cancelled; create a revert PR instead"),{status:409});if(pr.state==="closed")return{number:n,url:pr.html_url,state:"closed",idempotent:true};const out=await request("PATCH",api("/pulls/"+n),{state:"closed"});return{number:n,url:out.data.html_url,state:out.data.state||"closed",idempotent:false}}
  async function createRevertPR(number,options={}){
    const n=Number(number);if(!Number.isInteger(n)||n<1)throw Object.assign(Error("Valid pull request number required"),{status:400});
    const slug=String(options.slug||"").toLowerCase().replace(/[^a-z0-9-]/g,"-").replace(/-+/g,"-").replace(/^-|-$/g,"");
    if(!slug)throw Object.assign(Error("Article slug is required for a safe targeted revert"),{status:400});
    const pr=await getJson("/pulls/"+n);if(!pr.merged||!pr.merge_commit_sha)throw Object.assign(Error("Only merged publisher PRs can be reverted"),{status:409});
    const base=await getJson("/git/ref/heads/"+encodeURIComponent(baseBranch)),baseSha=base.object?.sha;if(!baseSha)throw Error("Unable to resolve public-site main branch");
    const branch="area-seo/revert-pr-"+n+"-"+String(baseSha).slice(0,8);
    const open=await getJson("/pulls?state=open&head="+encodeURIComponent(owner+":"+branch)+"&base="+encodeURIComponent(baseBranch));
    if(Array.isArray(open)&&open[0])return{mode:"revert-pull-request",repository:repoFull,sourcePr:n,branch,baseSha,files:[],pr:{number:open[0].number,url:open[0].html_url,title:open[0].title},merged:false,idempotent:true};
    const mergeCommit=await getJson("/git/commits/"+encodeURIComponent(pr.merge_commit_sha)),parent=mergeCommit.parents?.[0]?.sha,mergeTreeSha=mergeCommit.tree?.sha;
    if(!parent||!mergeTreeSha)throw Object.assign(Error("Merge commit ancestry unavailable"),{status:409});
    const [parentCommit,currentCommit]=await Promise.all([getJson("/git/commits/"+encodeURIComponent(parent)),getJson("/git/commits/"+encodeURIComponent(baseSha))]);
    const parentTreeSha=parentCommit.tree?.sha,currentTreeSha=currentCommit.tree?.sha;
    if(!parentTreeSha||!currentTreeSha)throw Error("Unable to resolve publisher revert trees");
    const [parentTree,mergeTree,currentTree]=await Promise.all([
      getJson("/git/trees/"+encodeURIComponent(parentTreeSha)+"?recursive=1"),
      getJson("/git/trees/"+encodeURIComponent(mergeTreeSha)+"?recursive=1"),
      getJson("/git/trees/"+encodeURIComponent(currentTreeSha)+"?recursive=1")
    ]);
    const map=t=>new Map((t.tree||[]).filter(x=>x.type==="blob").map(x=>[x.path,{path:x.path,sha:x.sha,mode:x.mode,type:x.type}]));
    const before=map(parentTree),merged=map(mergeTree),current=map(currentTree);
    const same=(a,b)=>(!a&&!b)||Boolean(a&&b&&a.sha===b.sha&&a.mode===b.mode&&a.type===b.type);
    const paths=[...new Set([...before.keys(),...merged.keys()])].filter(p=>!same(before.get(p),merged.get(p)));
    const allowed=new Set(["article-"+slug+".html","articles.html","sitemap.xml"]);
    const unexpected=paths.filter(p=>!allowed.has(p));
    if(unexpected.length)throw Object.assign(Error("Source publisher PR changed unexpected paths; manual revert required"),{status:409,paths:unexpected});
    if(!paths.length)throw Object.assign(Error("Publisher PR has no reversible file changes"),{status:409});
    const changes=[];
    for(const path of paths){
      const oldEntry=before.get(path)||null,newEntry=merged.get(path)||null,liveEntry=current.get(path)||null;
      if(same(liveEntry,oldEntry))continue;
      if(!same(liveEntry,newEntry))throw Object.assign(Error("Cannot safely revert "+path+" because it changed after publisher PR #"+n),{status:409,path});
      changes.push(oldEntry?{path,mode:oldEntry.mode,type:"blob",sha:oldEntry.sha}:{path,sha:null});
    }
    if(!changes.length)return{mode:"already-reverted",repository:repoFull,sourcePr:n,branch:null,baseSha,files:[],pr:null,merged:false,idempotent:true};
    let exists=false;try{await getJson("/git/ref/heads/"+encodeURIComponent(branch));exists=true}catch(e){if(e.statusCode!==404)throw e}
    if(exists)throw Object.assign(Error("Revert branch already exists without an open PR; manual review required"),{status:409});
    await request("POST",api("/git/refs"),{ref:"refs/heads/"+branch,sha:baseSha});
    const newTree=await request("POST",api("/git/trees"),{base_tree:currentTreeSha,tree:changes});
    const treeSha=newTree.data.sha;if(!treeSha)throw Error("Unable to create targeted revert tree");
    const newCommit=await request("POST",api("/git/commits"),{message:"revert: publisher PR #"+n,tree:treeSha,parents:[baseSha]});
    await request("PATCH",api("/git/refs/heads/"+encodeURIComponent(branch)),{sha:newCommit.data.sha,force:false});
    const out=await request("POST",api("/pulls"),{title:"Revert SEO publisher PR #"+n,head:branch,base:baseBranch,body:"Targeted recovery PR generated by AREA SEO AI. It reverts only files changed by publisher PR #"+n+" and refuses to overwrite later edits. Review the diff and CI before merging. Do not merge automatically."});
    const revert=out.data;
    return{mode:"revert-pull-request",repository:repoFull,sourcePr:n,branch,baseSha,files:changes.map(x=>x.path),pr:{number:revert.number,url:revert.html_url,title:revert.title},merged:false,idempotent:false};
  }
  async function getPublishStatus(number){
    const n=Number(number);if(!Number.isInteger(n)||n<1)throw Object.assign(Error("Valid pull request number required"),{status:400});
    const pr=await getJson("/pulls/"+n),sha=pr.head?.sha||null;let combined={state:"unknown",statuses:[]};
    if(sha){try{combined=await getJson("/commits/"+sha+"/status")}catch(e){if(e.statusCode!==404)throw e}}
    return {repository:repoFull,number:n,url:pr.html_url,title:pr.title,state:pr.state,merged:Boolean(pr.merged),mergeable:pr.mergeable,branch:pr.head?.ref||null,headSha:sha,base:pr.base?.ref||baseBranch,ci:{state:combined.state||"unknown",statuses:(combined.statuses||[]).map(s=>({context:s.context,state:s.state,description:s.description,target_url:s.target_url}))},updatedAt:pr.updated_at||null};
  }
  return {configured:Boolean(token),repository:repoFull,baseBranch,safeBranch,getPublishBase,createPublishPR,closePublishPR,createRevertPR,getPublishStatus};
}
module.exports={createClient,parseRepo,safeBranch};
