const https=require("https");

function parseRepo(value){
  const m=String(value||"").trim().match(/^([A-Za-z0-9_.-]+)\/([A-Za-z0-9_.-]+)$/);
  if(!m)throw Error("PUBLISH_REPO must be owner/repo");
  return {owner:m[1],repo:m[2]};
}
function safeBranch(slug){
  const s=String(slug||"").toLowerCase().replace(/[^a-z0-9-]/g,"-").replace(/-+/g,"-").replace(/^-|-$/g,"").slice(0,70);
  if(!s)throw Error("Valid article slug required");
  return "area-seo/article-"+s;
}
function createClient(opts={}){
  const token=String(opts.token||process.env.GITHUB_PUBLISH_TOKEN||"").trim();
  const repoFull=opts.repo||process.env.PUBLISH_REPO||"jmmeta6767/area-maibab-public-site";
  const baseBranch=opts.baseBranch||process.env.PUBLISH_BRANCH||"main";
  const {owner,repo}=parseRepo(repoFull);
  if(baseBranch!=="main")throw Error("Publisher base branch must be main");
  const request=opts.request||((method,path,body)=>new Promise((resolve,reject)=>{
    if(!token)return reject(Object.assign(Error("GITHUB_PUBLISH_TOKEN is not configured"),{status:503}));
    const payload=body===undefined?null:JSON.stringify(body);
    const req=https.request({hostname:"api.github.com",path,method,headers:{
      "Accept":"application/vnd.github+json","Authorization":"Bearer "+token,
      "X-GitHub-Api-Version":"2022-11-28","User-Agent":"AREA-SEO-AI/1.9",
      ...(payload?{"Content-Type":"application/json","Content-Length":Buffer.byteLength(payload)}:{})
    }},res=>{let data="";res.on("data",c=>data+=c);res.on("end",()=>{
      let parsed={};try{parsed=data?JSON.parse(data):{}}catch{parsed={message:data}}
      if(res.statusCode>=200&&res.statusCode<300)return resolve({status:res.statusCode,data:parsed});
      const e=Error(parsed.message||("GitHub HTTP "+res.statusCode));e.statusCode=res.statusCode;e.response=parsed;reject(e);
    })});
    req.setTimeout(20000,()=>req.destroy(Error("GitHub publisher timeout")));req.on("error",reject);if(payload)req.write(payload);req.end();
  }));
  const api=p=>"/repos/"+encodeURIComponent(owner)+"/"+encodeURIComponent(repo)+p;
  async function getJson(path){return (await request("GET",api(path))).data}
  const contentPath=p=>"/contents/"+String(p).split("/").map(encodeURIComponent).join("/");
  async function getPublishBase(slug){
    const base=await getJson("/git/ref/heads/"+encodeURIComponent(baseBranch)),baseSha=base.object?.sha;if(!baseSha)throw Error("Unable to resolve public-site main branch");
    const read=async p=>{const x=await getJson(contentPath(p)+"?ref="+encodeURIComponent(baseBranch));return{path:p,sha:x.sha,content:Buffer.from(x.content||"","base64").toString("utf8")}};
    const article="article-"+String(slug||"")+".html";let articleExists=false;try{await getJson(contentPath(article)+"?ref="+encodeURIComponent(baseBranch));articleExists=true}catch(e){if(e.statusCode!==404)throw e}
    const [articlesHtml,sitemapXml]=await Promise.all([read("articles.html"),read("sitemap.xml")]);return{baseSha,articleExists,articlesHtml,sitemapXml};
  }
  async function createPublishPR(item,pkg,options={}){
    if(!item||item.status!=="approved")throw Object.assign(Error("Draft must be approved before publishing"),{status:422});
    if(!pkg?.files?.length)throw Object.assign(Error("Publisher package is empty"),{status:422});
    const allowed=new Set([pkg.article?.filename,"articles.html","sitemap.xml"]);
    if(pkg.files.some(f=>!allowed.has(f.path)))throw Object.assign(Error("Publisher package contains an unexpected path"),{status:422});
    const branch=safeBranch(item.slug),base=await getJson("/git/ref/heads/"+encodeURIComponent(baseBranch));
    const baseSha=base.object?.sha;if(!baseSha)throw Error("Unable to resolve public-site main branch");
    if(options.expectedBaseSha&&options.expectedBaseSha!==baseSha)throw Object.assign(Error("Public site main changed; rebuild package and retry"),{status:409});
    let branchExists=false;
    try{await getJson("/git/ref/heads/"+encodeURIComponent(branch));branchExists=true}catch(e){if(e.statusCode!==404)throw e}
    if(!branchExists)await request("POST",api("/git/refs"),{ref:"refs/heads/"+branch,sha:baseSha});
    const written=[];
    for(const file of pkg.files){
      let sha;try{const cur=await getJson(contentPath(file.path)+"?ref="+encodeURIComponent(branch));sha=cur.sha}catch(e){if(e.statusCode!==404)throw e}
      const payload={message:"seo: publish "+item.slug+" ("+file.path+")",content:Buffer.from(file.content,"utf8").toString("base64"),branch};
      if(sha)payload.sha=sha;
      const out=await request("PUT",api(contentPath(file.path)),payload);written.push({path:file.path,commit:out.data.commit?.sha||null});
    }
    const pulls=await getJson("/pulls?state=open&head="+encodeURIComponent(owner+":"+branch)+"&base="+encodeURIComponent(baseBranch));
    let pr=Array.isArray(pulls)&&pulls[0];
    if(!pr){
      const out=await request("POST",api("/pulls"),{title:"SEO: "+item.title,head:branch,base:baseBranch,body:"Generated by AREA SEO AI after SEO audit and human approval.\\n\\nArticle: "+pkg.article.filename+"\\n\\nReview the diff and CI before merging. Do not merge automatically."});
      pr=out.data;
    }
    return {mode:"pull-request",repository:repoFull,base:baseBranch,branch,baseSha,files:written,pr:{number:pr.number,url:pr.html_url,title:pr.title},merged:false};
  }
  async function getPublishStatus(number){
    const n=Number(number);if(!Number.isInteger(n)||n<1)throw Object.assign(Error("Valid pull request number required"),{status:400});
    const pr=await getJson("/pulls/"+n),sha=pr.head?.sha||null;let combined={state:"unknown",statuses:[]};
    if(sha){try{combined=await getJson("/commits/"+sha+"/status")}catch(e){if(e.statusCode!==404)throw e}}
    return {repository:repoFull,number:n,url:pr.html_url,title:pr.title,state:pr.state,merged:Boolean(pr.merged),mergeable:pr.mergeable,branch:pr.head?.ref||null,headSha:sha,base:pr.base?.ref||baseBranch,ci:{state:combined.state||"unknown",statuses:(combined.statuses||[]).map(s=>({context:s.context,state:s.state,description:s.description,target_url:s.target_url}))},updatedAt:pr.updated_at||null};
  }
  return {configured:Boolean(token),repository:repoFull,baseBranch,safeBranch,getPublishBase,createPublishPR,getPublishStatus};
}
module.exports={createClient,parseRepo,safeBranch};
